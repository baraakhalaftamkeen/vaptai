"""_is_proof_finding: proof-source + confirmed=True auto-promotes; everything else stays `candidate`.

Regression test for the DineHub run of 2026-10-22, where a mis-flipped `or` promoted
every observation from a proof-source tool — including the "no vuln signature matched"
diagnostics web_param_probe/ssti_detect/sqli_detect emit on a miss — to CONFIRMED. The
reported confirmed count was 20 on a run with only ~2 actual proof-confirmed web vulns.

The invariant these tests lock:
  * source_tool ∈ _PROOF_SOURCE_TOOLS AND detail.confirmed == True → promote
  * source_tool ∈ _PROOF_SOURCE_TOOLS AND detail.confirmed == False → DO NOT promote
  * source_tool ∈ _PROOF_SOURCE_TOOLS AND detail.confirmed missing → DO NOT promote
  * source_tool ∉ _PROOF_SOURCE_TOOLS → DO NOT promote regardless of confirmed flag
"""
from __future__ import annotations

import pytest

from vapt_agents import phases
from vapt_persistence import Base, init_engine
import vapt_persistence.db as dbmod
from vapt_persistence.models import (
    Engagement,
    Finding,
    FindingObservation,
    Project,
    Run,
)


@pytest.fixture()
def db(tmp_path):
    """Mirror the fixture pattern used by tests/test_normalize_grounding.py so the two
    don't drift. ids are autogenerated by pk_column so constructors stay terse."""
    init_engine(f"sqlite:///{tmp_path}/t.db")
    Base.metadata.create_all(dbmod.get_engine())
    s = dbmod.SessionLocal()
    p = Project(name="P"); s.add(p); s.flush()
    e = Engagement(project_id=p.id, name="L", testing_mode="black_box",
                   target_type="web"); s.add(e); s.flush()
    r = Run(engagement_id=e.id, thread_id="t", status="running"); s.add(r); s.flush()
    s.commit()
    yield s, r.id
    s.close()


def _mk_finding(sess, run_id: str) -> str:
    f = Finding(run_id=run_id, title="f", severity="info", status="candidate")
    sess.add(f); sess.flush(); sess.commit()
    return f.id


def _add_obs(sess, finding_id: str, source_tool: str, detail: dict | None = None) -> None:
    sess.add(FindingObservation(finding_id=finding_id, source_tool=source_tool,
                                detail=(detail or {})))
    sess.commit()


def test_proof_source_with_confirmed_true_promotes(db):
    s, run_id = db
    fid = _mk_finding(s, run_id)
    _add_obs(s, fid, "sqli_detect", {"confirmed": True})
    assert phases._is_proof_finding(s, fid) is True


def test_proof_source_without_confirmed_key_does_not_promote(db):
    """The regression. web_param_probe emits a "no vuln signature matched" trace
    observation on a miss, with NO `confirmed` key in detail. Before the fix this
    was promoted to CONFIRMED anyway because the predicate used `or`."""
    s, run_id = db
    fid = _mk_finding(s, run_id)
    _add_obs(s, fid, "web_param_probe",
             {"class": "sqli", "evidence": "", "trace": [{"status": 200}]})
    assert phases._is_proof_finding(s, fid) is False


def test_proof_source_with_confirmed_false_does_not_promote(db):
    """idor_probe/dalfox/web_param_probe HIT observations carry
    `confirmed: True|False`. A False (candidate IDOR / unverified dalfox reflect
    / probe signature mismatch) must stay `candidate`."""
    s, run_id = db
    fid = _mk_finding(s, run_id)
    _add_obs(s, fid, "dalfox", {"confirmed": False, "verified": False})
    assert phases._is_proof_finding(s, fid) is False


def test_non_proof_source_never_promotes_even_if_confirmed_true(db):
    """nuclei/wapiti/arjun are explicitly OUT of _PROOF_SOURCE_TOOLS by design
    (the comment above the set says so). A hallucinated or tampered observation
    that claims `confirmed=True` from one of those tools must NOT promote the
    finding."""
    s, run_id = db
    fid = _mk_finding(s, run_id)
    _add_obs(s, fid, "wapiti", {"confirmed": True})
    assert phases._is_proof_finding(s, fid) is False


def test_sqli_detect_miss_diagnostic_does_not_promote(db):
    """The sqli_detect normalizer wraps the parser with a diagnostic observation on
    miss (`sqli_detect: no SQL injection detected`, severity info, no `confirmed`
    key). That diagnostic must not promote the finding — the whole reason the
    diagnostic exists is to make a miss visible without inflating the confirmed count."""
    s, run_id = db
    fid = _mk_finding(s, run_id)
    _add_obs(s, fid, "sqli_detect",
             {"stderr_tail": "", "stdout_tail": "all tested parameters do not appear to be injectable"})
    assert phases._is_proof_finding(s, fid) is False


def test_sstimap_miss_diagnostic_does_not_promote(db):
    s, run_id = db
    fid = _mk_finding(s, run_id)
    _add_obs(s, fid, "sstimap", {"stderr_tail": "", "stdout_tail": ""})
    assert phases._is_proof_finding(s, fid) is False


def test_mixed_observations_promote_on_any_true_proof_obs(db):
    """A finding with a mix of a diagnostic (no confirmed) and a true-confirmed
    hit observation still promotes — the real proof is the one that counts."""
    s, run_id = db
    fid = _mk_finding(s, run_id)
    _add_obs(s, fid, "sqli_detect", {"stdout_tail": "ambiguous"})
    _add_obs(s, fid, "sqli_detect", {"confirmed": True, "params": ["id"]})
    assert phases._is_proof_finding(s, fid) is True
